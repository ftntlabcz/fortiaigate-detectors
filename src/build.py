import json, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from detectors import CATS, DETECTORS
from topics import TOPICS

nodes = [{"id": "hub", "type": "hub", "label": {k: "FortiAIGate" for k in ("en", "cs", "sk")}}]
links = []
for ck, lab in CATS.items():
    nodes.append({"id": "c:" + ck, "type": "cat", "label": lab})
    links.append({"source": "hub", "target": "c:" + ck})
used = set()
for name, cat, region, rules, tks, url, desc in DETECTORS:
    did = "d:" + name
    nodes.append({"id": did, "type": "det", "region": region, "rules": rules, "cat": "c:" + cat,
                  "label": {k: name for k in ("en", "cs", "sk")}, "url": url, "desc": desc})
    links.append({"source": "c:" + cat, "target": did})
    for t in tks:
        assert t in TOPICS, (name, t)
        used.add(t)
        links.append({"source": did, "target": "t:" + t})
for k in TOPICS:
    if k not in used:
        continue
    en, cs, sk, url, src, den, dcs, dsk = TOPICS[k]
    nodes.append({"id": "t:" + k, "type": "topic", "label": {"en": en, "cs": cs, "sk": sk},
                  "url": url, "src": src, "desc": {"en": den, "cs": dcs, "sk": dsk}})
unused = set(TOPICS) - used
data = {"version": "FortiAIGate 8.0.2", "nodes": nodes, "links": links}
out = sys.argv[1]
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by build.py from detectors.py and topics.py. Do not edit by hand.\n")
    f.write("window.DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
from collections import Counter
print("detectors", len(DETECTORS), "topics", len(used), "unused", unused, Counter(d[2] for d in DETECTORS))
